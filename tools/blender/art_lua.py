"""Write src/shared/Content/ArtMeshes.luau from the uploaded model set (build/art/roblox.json, read from Studio after the
upload) and its colours (build/art/art.json, from mada_art.py).

  python tools/blender/art_lua.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
ids = json.loads((ROOT / "build" / "art" / "roblox.json").read_text(encoding="utf-8"))["LV Mada art set"]
meta = json.loads((ROOT / "build" / "art" / "art.json").read_text(encoding="utf-8"))
items = {}
for name, p in ids.items():
    item, part = name.split("_", 1)
    items.setdefault(item, []).append((part, p, meta[name]["rgb"]))
lines = ["-- Generated by tools/blender/mada_art.py + art_lua.py (do not edit by hand): Làng Vọng's own models, each one Blender",
         "-- build split by material. Per item, its pieces: { part, mesh id, size, at = centre offset from the item's origin,",
         "-- color }. Asset 'LV Mada art set' (Raumania group). Note: Blender's left is Roblox's right (Face's HairL sits at +x).",
         "return {"]
for item in sorted(items):
    lines.append(f"\t{item} = {{")
    for part, p, rgb in sorted(items[item]):
        sx, sy, sz = p["mesh_size"]
        x, y, z = p["pos"]
        lines.append(f"\t\t{{ part = \"{part}\", id = \"{p['mesh']}\", size = Vector3.new({sx:.3f}, {sy:.3f}, {sz:.3f}), "
                     f"at = Vector3.new({x:.3f}, {y:.3f}, {z:.3f}), color = Color3.fromRGB({rgb[0]}, {rgb[1]}, {rgb[2]}) }},")
    lines.append("\t},")
lines.append("}")
out = ROOT / "src" / "shared" / "Content" / "ArtMeshes.luau"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(out, len(items), "items")
